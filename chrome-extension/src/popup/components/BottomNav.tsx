interface TabDef {
  id: TabId;
  label: string;
  Icon: () => JSX.Element;
}

const TABS: TabDef[] = [
  { id: "brands",    label: "Brands",    Icon: BrandsIcon },
  { id: "selectors", label: "Selectors", Icon: SelectorsIcon },
  { id: "history",   label: "History",   Icon: HistoryIcon },
  { id: "settings",  label: "Settings",  Icon: SettingsIcon },
];

interface Props {
  activeTab: TabId;
  onTabChange: (tab: TabId) => void;
}

export function BottomNav({ activeTab, onTabChange }: Props) {
  return (
    <div className="flex border-t border-line bg-surface flex-shrink-0 h-[52px]">
      {TABS.map((tab) => {
        const active = activeTab === tab.id;
        return (
          <button
            key={tab.id}
            onClick={() => onTabChange(tab.id)}
            className={`flex-1 flex flex-col items-center justify-center gap-[3px] transition relative ${
              active ? "text-primary" : "text-t3 hover:text-t2"
            }`}
          >
            {active && (
              <span className="absolute top-0 left-3 right-3 h-[2px] bg-primary rounded-b-full" />
            )}
            <tab.Icon />
            <span className="text-[7.5px] font-bold uppercase tracking-[0.05em] leading-none">{tab.label}</span>
          </button>
        );
      })}
    </div>
  );
}
